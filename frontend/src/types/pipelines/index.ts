import { User } from "../user";
import { ModelVersion } from "../models";
import { OwnerType } from "../enums";

/** Lifecycle status of a pipeline definition. Mirrors the backend `PipelineStatus` enum. */
export enum PipelineStatus {
  DRAFT = "draft",
  VALIDATED = "validated",
  ARCHIVED = "archived",
}

/**
 * Where a step's model came from: an upload made while building the pipeline,
 * or a reference to an already-uploaded model. Mirrors `PipelineStepSource`.
 */
export enum PipelineStepSource {
  NEW_UPLOAD = "new_upload",
  EXISTING = "existing",
}

/** Whether a step is pinned to an exact model version or tracks the latest READY one. */
export enum PipelinePinPolicy {
  PINNED = "pinned",
  LATEST_READY = "latest_ready",
}

/** Review status of an edge's mapper. Mirrors `PipelineEdgeStatus`. */
export enum PipelineEdgeStatus {
  MANUAL = "manual",
  OK = "ok",
  NEEDS_REVIEW = "needs_review",
}

/** Overall execution status of a pipeline run. Mirrors `PipelineRunStatus`. */
export enum PipelineRunStatus {
  PENDING = "pending",
  RUNNING = "running",
  SUCCESS = "success",
  FAILED = "failed",
  PARTIAL = "partial",
}

/** Execution status of a single step within a run. Mirrors `PipelineStepRunStatus`. */
export enum PipelineStepRunStatus {
  PENDING = "pending",
  RUNNING = "running",
  SUCCESS = "success",
  FAILED = "failed",
  SKIPPED = "skipped",
}

/** A single declarative field-mapping rule, as interpreted by the backend's MapperEngineService. */
export type MapperRule =
  | { op: "copy"; from: string; to: string }
  | { op: "default"; to: string; value: unknown }
  | { op: "cast"; from: string; to: string; as: "string" | "number" | "boolean" }
  | { op: "template"; to: string; template: string };

/** The declarative mapping spec stored on a `PipelineEdge`. An empty `rules` array passes the payload through unchanged. */
export interface MapperSpec {
  rules: MapperRule[];
}

/** A step's model version, with the owning model's name/id nested in for display. */
export type PipelineStepModelVersion = ModelVersion & {
  model?: { id: string; name: string };
};

/** One node in a pipeline's chain: a model call. */
export interface PipelineStep {
  id: string;
  order: number;
  label?: string | null;
  source: PipelineStepSource;
  modelVersion: PipelineStepModelVersion | null;
  pinPolicy: PipelinePinPolicy;
  timeoutMs?: number | null;
  maxRetries: number;
  createdAt: string;
  updatedAt: string;
}

/** The transform applied between two steps (or the pipeline's external input/output). */
export interface PipelineEdge {
  id: string;
  fromStep: Pick<PipelineStep, "id" | "order" | "label"> | null;
  toStep: Pick<PipelineStep, "id" | "order" | "label"> | null;
  spec: MapperSpec;
  autoGenerated: boolean;
  confidence: number | null;
  status: PipelineEdgeStatus;
  createdAt: string;
  updatedAt: string;
}

/** The reusable pipeline definition. */
export interface Pipeline {
  id: string;
  name: string;
  description?: string | null;
  user?: User;
  status: PipelineStatus;
  version: number;
  steps?: PipelineStep[];
  createdAt: string;
  updatedAt: string;
}

/** Execution record for one step within a run. */
export interface PipelineStepRun {
  id: string;
  order: number;
  step?: Pick<PipelineStep, "id" | "order" | "label">;
  mappedInput: Record<string, unknown> | null;
  output: Record<string, unknown> | null;
  status: PipelineStepRunStatus;
  cost: number;
  responseTimeMs: number | null;
  errorMessage: string | null;
  createdAt: string;
}

/** One execution of a pipeline: the audit trail of input, output, cost, and per-step results. */
export interface PipelineRun {
  id: string;
  pipeline?: Pick<Pipeline, "id" | "name">;
  pipelineVersion: number;
  workspaceId: string;
  workspaceType: OwnerType;
  input: Record<string, unknown>;
  output: Record<string, unknown> | null;
  status: PipelineRunStatus;
  totalCost: number;
  totalLatencyMs: number | null;
  errorMessage: string | null;
  stepRuns?: PipelineStepRun[];
  createdAt: string;
  updatedAt: string;
}
