import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  UpdateDateColumn,
  ManyToOne,
  OneToMany,
} from 'typeorm';
import { User } from '../../users/entities/user.entity';
import { Organization } from '../../organizations/entities/organization.entity';
import { PipelineStatus } from '../enums/pipeline-status.enum';
import { PipelineType } from '../enums/pipeline-type.enum';
import { PipelineStep } from './pipeline-step.entity';
import { PipelineRun } from './pipeline-run.entity';

/**
 * A reusable chain of model-calling steps, grouped into stages. The output of
 * a stage is transformed by one or more {@link PipelineEdge} mappers into the
 * input of the next stage — steps sharing a stage run concurrently, so the
 * same edge-based mapper mechanism expresses sequential, context-augmented,
 * and parallel/fan-out-fan-in shapes alike.
 */
@Entity('pipelines')
export class Pipeline {
  /**
   * Unique UUID identifier generated by the database.
   */
  @PrimaryGeneratedColumn('uuid')
  id: string;

  /**
   * Display name of the pipeline.
   */
  @Column()
  name: string;

  /**
   * Optional long-form explanation of what the pipeline does.
   */
  @Column({ type: 'varchar', nullable: true })
  description: string | null;

  /**
   * Owner user account that created this pipeline.
   */
  @ManyToOne(() => User)
  user: User;

  /**
   * Optional owning organization, mirroring model ownership.
   */
  @ManyToOne(() => Organization, { nullable: true })
  organization: Organization | null;

  /**
   * Lifecycle status. Only `VALIDATED` pipelines may be run.
   */
  @Column({
    type: 'varchar',
    enum: PipelineStatus,
    default: PipelineStatus.DRAFT,
  })
  status: PipelineStatus;

  /**
   * UI preset describing the pipeline's intended shape (sequential,
   * context-augmented, or parallel). Metadata only — does not change how the
   * pipeline is executed or validated.
   */
  @Column({
    type: 'varchar',
    enum: PipelineType,
    default: PipelineType.SEQUENTIAL_CHAIN,
  })
  type: PipelineType;

  /**
   * Increments on every edit; recorded on each {@link PipelineRun} for
   * reproducibility.
   */
  @Column({ default: 1 })
  version: number;

  /**
   * Visibility flag indicating whether this pipeline is listed in the
   * public marketplace, mirroring {@link Model.isPublic}.
   */
  @Column({ type: 'boolean', default: false })
  isPublic: boolean;

  /**
   * Ordered steps belonging to this pipeline.
   */
  @OneToMany(() => PipelineStep, (step) => step.pipeline)
  steps: PipelineStep[];

  /**
   * Execution history for this pipeline.
   */
  @OneToMany(() => PipelineRun, (run) => run.pipeline)
  runs: PipelineRun[];

  /**
   * Timestamp record indicating when this pipeline was created.
   */
  @CreateDateColumn()
  createdAt: Date;

  /**
   * Timestamp record indicating when this pipeline was last edited.
   */
  @UpdateDateColumn()
  updatedAt: Date;
}
