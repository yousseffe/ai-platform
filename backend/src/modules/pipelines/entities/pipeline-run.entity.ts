import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  UpdateDateColumn,
  ManyToOne,
  OneToMany,
} from 'typeorm';
import { Pipeline } from './pipeline.entity';
import { User } from '../../users/entities/user.entity';
import { OwnerType } from '../../../shared/enums/owner-type.enum';
import { PipelineRunStatus } from '../enums/pipeline-run-status.enum';
import { PipelineStepRun } from './pipeline-step-run.entity';

/**
 * One execution of a {@link Pipeline}: the audit trail of input, output,
 * total cost, and per-step results.
 */
@Entity('pipeline_runs')
export class PipelineRun {
  /**
   * Unique UUID identifier generated by the database.
   */
  @PrimaryGeneratedColumn('uuid')
  id: string;

  /**
   * The pipeline definition that was executed.
   */
  @ManyToOne(() => Pipeline, (pipeline) => pipeline.runs, {
    onDelete: 'CASCADE',
  })
  pipeline: Pipeline;

  /**
   * The pipeline `version` at the time of this run, for reproducibility.
   */
  @Column({ name: 'pipeline_version' })
  pipelineVersion: number;

  /**
   * User who triggered this run, if authenticated via JWT.
   */
  @ManyToOne(() => User, { nullable: true })
  triggeredBy: User | null;

  /**
   * Workspace (user or organization) billed for this run's step costs.
   */
  @Column({ name: 'workspace_id', type: 'uuid' })
  workspaceId: string;

  /**
   * Type of the billed workspace.
   */
  @Column({ name: 'workspace_type', type: 'varchar', enum: OwnerType })
  workspaceType: OwnerType;

  /**
   * The raw input payload submitted to the pipeline.
   */
  @Column({ type: 'jsonb' })
  input: Record<string, unknown>;

  /**
   * The final output payload, set once the run completes successfully.
   */
  @Column({ type: 'jsonb', nullable: true })
  output: Record<string, unknown> | null;

  /**
   * Overall execution status.
   */
  @Column({
    type: 'varchar',
    enum: PipelineRunStatus,
    default: PipelineRunStatus.PENDING,
  })
  status: PipelineRunStatus;

  /**
   * Sum of credits charged across all successfully executed steps.
   */
  @Column({
    name: 'total_cost',
    type: 'decimal',
    precision: 12,
    scale: 4,
    default: 0,
  })
  totalCost: number;

  /**
   * Total wall-clock duration of the run, in milliseconds.
   */
  @Column({ name: 'total_latency_ms', type: 'integer', nullable: true })
  totalLatencyMs: number | null;

  /**
   * Error message captured if the run failed or partially failed.
   */
  @Column({ name: 'error_message', type: 'text', nullable: true })
  errorMessage: string | null;

  /**
   * Per-step execution records for this run.
   */
  @OneToMany(() => PipelineStepRun, (stepRun) => stepRun.run)
  stepRuns: PipelineStepRun[];

  /**
   * Timestamp record indicating when this run started.
   */
  @CreateDateColumn()
  createdAt: Date;

  /**
   * Timestamp record indicating when this run's status last changed.
   */
  @UpdateDateColumn()
  updatedAt: Date;
}
