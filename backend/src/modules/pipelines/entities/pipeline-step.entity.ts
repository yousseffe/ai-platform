import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  UpdateDateColumn,
  ManyToOne,
} from 'typeorm';
import { Pipeline } from './pipeline.entity';
import { ModelVersion } from '../../models/entities/model-version.entity';
import { PipelineStepSource } from '../enums/pipeline-step-source.enum';
import { PipelinePinPolicy } from '../enums/pipeline-pin-policy.enum';

/**
 * One node in a pipeline: a model call. Steps are grouped into stages by
 * `order` — a stage with multiple steps runs them concurrently as parallel
 * branches. The model behind a step can come from an upload made while
 * building the pipeline (`NEW_UPLOAD`) or a reference to an already-uploaded
 * model the user or marketplace owns (`EXISTING`) — both ultimately resolve
 * to a `modelVersion`.
 */
@Entity('pipeline_steps')
export class PipelineStep {
  /**
   * Unique UUID identifier generated by the database.
   */
  @PrimaryGeneratedColumn('uuid')
  id: string;

  /**
   * Parent pipeline this step belongs to.
   */
  @ManyToOne(() => Pipeline, (pipeline) => pipeline.steps, {
    onDelete: 'CASCADE',
  })
  pipeline: Pipeline;

  /**
   * 0-based stage index. Steps sharing the same `order` within a pipeline
   * execute concurrently as parallel branches of that stage; stages
   * themselves still run in ascending `order`.
   */
  @Column()
  order: number;

  /**
   * Display label shown in the pipeline builder.
   */
  @Column({ type: 'varchar', nullable: true })
  label: string | null;

  /**
   * Disambiguates this step from its siblings when its stage (`order`) has
   * more than one step — e.g. `"summarizer"`, `"classifier"`. Used to key
   * this step's output under `steps.<order>.<role>` in mapper contexts.
   * Required only when a stage has multiple steps (enforced at validation).
   */
  @Column({ type: 'varchar', nullable: true })
  role: string | null;

  /**
   * Provenance of the model this step calls: a fresh upload bound during
   * pipeline authoring, or a reference to an existing model.
   */
  @Column({
    type: 'varchar',
    enum: PipelineStepSource,
    default: PipelineStepSource.EXISTING,
  })
  source: PipelineStepSource;

  /**
   * The model version this step calls. For `NEW_UPLOAD` steps this is set
   * once the upload's build completes; until then the step cannot run.
   */
  @ManyToOne(() => ModelVersion, { nullable: true })
  modelVersion: ModelVersion | null;

  /**
   * Whether this step is pinned to the exact `modelVersion` above (reproducible)
   * or should always resolve the latest READY version of that version's model.
   */
  @Column({
    type: 'varchar',
    enum: PipelinePinPolicy,
    default: PipelinePinPolicy.PINNED,
  })
  pinPolicy: PipelinePinPolicy;

  /**
   * Per-step request timeout override, in milliseconds.
   */
  @Column({ name: 'timeout_ms', type: 'integer', nullable: true })
  timeoutMs: number | null;

  /**
   * Number of retries on transient failure before failing the run.
   */
  @Column({ name: 'max_retries', type: 'integer', default: 0 })
  maxRetries: number;

  /**
   * Timestamp record indicating when this step was created.
   */
  @CreateDateColumn()
  createdAt: Date;

  /**
   * Timestamp record indicating when this step was last edited.
   */
  @UpdateDateColumn()
  updatedAt: Date;
}
