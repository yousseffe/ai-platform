import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  UpdateDateColumn,
  ManyToOne,
} from 'typeorm';
import { Pipeline } from './pipeline.entity';
import { PipelineStep } from './pipeline-step.entity';
import { PipelineEdgeStatus } from '../enums/pipeline-edge-status.enum';
import { MapperSpec } from '../interfaces/mapper-spec.interface';

/**
 * The transform applied between two steps. A null `fromStep` represents the
 * pipeline's external input; a null `toStep` represents its external output.
 * The `spec` is interpreted by {@link MapperEngineService} — it is never
 * executed as code.
 */
@Entity('pipeline_edges')
export class PipelineEdge {
  /**
   * Unique UUID identifier generated by the database.
   */
  @PrimaryGeneratedColumn('uuid')
  id: string;

  /**
   * Parent pipeline this edge belongs to.
   */
  @ManyToOne(() => Pipeline, { onDelete: 'CASCADE' })
  pipeline: Pipeline;

  /**
   * The step this edge reads output from. Null means the pipeline's external input.
   */
  @ManyToOne(() => PipelineStep, { nullable: true, onDelete: 'CASCADE' })
  fromStep: PipelineStep | null;

  /**
   * The step this edge feeds mapped input into. Null means the pipeline's external output.
   */
  @ManyToOne(() => PipelineStep, { nullable: true, onDelete: 'CASCADE' })
  toStep: PipelineStep | null;

  /**
   * The declarative field-mapping rules applied to the payload crossing this edge.
   * An empty rule list passes the payload through unchanged.
   */
  @Column({ type: 'jsonb', default: () => '\'{"rules":[]}\'' })
  spec: MapperSpec;

  /**
   * Whether `spec` was produced by the (future) auto-detector rather than hand-written.
   */
  @Column({ name: 'auto_generated', type: 'boolean', default: false })
  autoGenerated: boolean;

  /**
   * Detector confidence score (0-1) for auto-generated specs; null for manual ones.
   */
  @Column({ type: 'real', nullable: true })
  confidence: number | null;

  /**
   * Review status of this edge's mapping.
   */
  @Column({
    type: 'varchar',
    enum: PipelineEdgeStatus,
    default: PipelineEdgeStatus.MANUAL,
  })
  status: PipelineEdgeStatus;

  /**
   * Timestamp record indicating when this edge was created.
   */
  @CreateDateColumn()
  createdAt: Date;

  /**
   * Timestamp record indicating when this edge was last edited.
   */
  @UpdateDateColumn()
  updatedAt: Date;
}
