import { Injectable, NotFoundException } from '@nestjs/common';
import { InjectRepository } from '@nestjs/typeorm';
import { IsNull, Repository } from 'typeorm';
import { PipelineEdge } from '../entities/pipeline-edge.entity';
import { PipelineStep } from '../entities/pipeline-step.entity';
import { PipelineEdgeStatus } from '../enums/pipeline-edge-status.enum';
import { UpsertEdgeDto } from '../dto/upsert-edge.dto';
import { PipelinesService } from './pipelines.service';

/**
 * Manages the mapper attached to each edge between (or into/out of) pipeline
 * steps. Replacing an edge's mapper demotes the parent pipeline to `DRAFT`.
 */
@Injectable()
export class PipelineEdgesService {
  constructor(
    @InjectRepository(PipelineEdge)
    private readonly edgeRepository: Repository<PipelineEdge>,
    @InjectRepository(PipelineStep)
    private readonly stepRepository: Repository<PipelineStep>,
    private readonly pipelinesService: PipelinesService,
  ) {}

  /** Lists all edges defined for a pipeline. */
  async listEdges(
    pipelineId: string,
    actorId: string,
  ): Promise<PipelineEdge[]> {
    await this.pipelinesService.getPipeline(pipelineId, actorId);
    return this.edgeRepository.find({
      where: { pipeline: { id: pipelineId } },
      relations: ['fromStep', 'toStep'],
    });
  }

  /**
   * Creates or replaces the edge between the given `fromStepId`/`toStepId`
   * pair (one or both may be omitted to represent the pipeline's external
   * input/output).
   *
   * @throws {NotFoundException} If a referenced step ID doesn't belong to the pipeline.
   */
  async upsertEdge(
    pipelineId: string,
    actorId: string,
    dto: UpsertEdgeDto,
  ): Promise<PipelineEdge> {
    await this.pipelinesService.getPipeline(pipelineId, actorId);
    const fromStep = await this.resolveStep(pipelineId, dto.fromStepId);
    const toStep = await this.resolveStep(pipelineId, dto.toStepId);

    const existing = await this.edgeRepository.findOne({
      where: {
        pipeline: { id: pipelineId },
        fromStep: fromStep ? { id: fromStep.id } : IsNull(),
        toStep: toStep ? { id: toStep.id } : IsNull(),
      },
    });

    const edge = this.edgeRepository.create({
      ...existing,
      pipeline: { id: pipelineId } as PipelineEdge['pipeline'],
      fromStep,
      toStep,
      spec: dto.spec,
      autoGenerated: false,
      status: PipelineEdgeStatus.MANUAL,
    });
    const saved = await this.edgeRepository.save(edge);
    await this.pipelinesService.demoteToDraft(pipelineId);
    return saved;
  }

  /** Deletes an edge by ID. */
  async removeEdge(
    pipelineId: string,
    edgeId: string,
    actorId: string,
  ): Promise<void> {
    await this.pipelinesService.getPipeline(pipelineId, actorId);
    const edge = await this.edgeRepository.findOne({
      where: { id: edgeId, pipeline: { id: pipelineId } },
    });
    if (!edge) {
      throw new NotFoundException('Pipeline edge not found');
    }
    await this.edgeRepository.remove(edge);
    await this.pipelinesService.demoteToDraft(pipelineId);
  }

  private async resolveStep(
    pipelineId: string,
    stepId: string | undefined,
  ): Promise<PipelineStep | null> {
    if (!stepId) {
      return null;
    }
    const step = await this.stepRepository.findOne({
      where: { id: stepId, pipeline: { id: pipelineId } },
    });
    if (!step) {
      throw new NotFoundException(`Step ${stepId} not found in this pipeline`);
    }
    return step;
  }
}
