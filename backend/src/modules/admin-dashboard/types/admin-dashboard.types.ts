/**
 * Supported formatting hints for admin KPI cards.
 */
export type AdminMetricFormat = 'number' | 'currency';

/**
 * Trend direction for a metric comparison.
 */
export type AdminMetricTrend = 'up' | 'down' | 'flat';

/**
 * Single KPI card returned to the admin dashboard overview.
 */
export interface AdminMetricCard {
  /** Stable frontend key. */
  key: string;
  /** Human-readable card title. */
  label: string;
  /** Current metric value. */
  value: number;
  /** Previous comparable period value. */
  previousValue: number;
  /** Percent change versus previous value. */
  changePercent: number | null;
  /** Trend direction. */
  trend: AdminMetricTrend;
  /** Link to the relevant admin surface. */
  href: string;
  /** Formatting hint for the UI. */
  format: AdminMetricFormat;
}

/**
 * Lightweight provider row used in overview widgets.
 */
export interface AdminTopProvider {
  /** Provider account UUID. */
  id: string;
  /** Provider display name. */
  name: string;
  /** Total provider earnings in EGP. */
  totalEarnings: number;
  /** Count of published models. */
  publicModels: number;
  /** Current tier display name. */
  tierName: string;
}

/**
 * High-level dashboard overview payload.
 */
export interface AdminDashboardOverview {
  /** Response generation timestamp. */
  generatedAt: string;
  /** KPI cards grouped for the overview. */
  cards: AdminMetricCard[];
  /** Highest-earning providers. */
  topProviders: AdminTopProvider[];
}

/**
 * Owner identity snapshot for provider admin pages.
 */
export interface AdminProviderOwnerSummary {
  /** Owner type discriminator. */
  ownerType: 'USER' | 'ORG';
  /** Owner UUID. */
  ownerId: string;
  /** Provider-facing owner label. */
  ownerName: string;
  /** Primary owner contact email if known. */
  ownerEmail: string | null;
}

/**
 * Derived subscription/payment state for a provider account.
 */
export interface AdminProviderSubscriptionSnapshot {
  /** Computed subscription state. */
  status: 'FREE' | 'ACTIVE' | 'PENDING' | 'SUSPENDED';
  /** Latest observed billing cycle. */
  billingCycle: 'MONTHLY' | 'ANNUAL' | null;
  /** Most recent confirmed payment date. */
  lastPaymentDate: string | null;
  /** Estimated next renewal date. */
  nextRenewalDate: string | null;
  /** Most recent subscription payment amount. */
  lastPaymentAmountEgp: number | null;
}

/**
 * Provider list row returned by the admin providers endpoint.
 */
export interface AdminProviderListItem {
  /** Provider account UUID. */
  id: string;
  /** Provider display name. */
  providerName: string;
  /** Owner snapshot. */
  owner: AdminProviderOwnerSummary;
  /** Current tier name. */
  currentTier: string;
  /** Provider lifecycle status. */
  providerStatus: string;
  /** Derived subscription state. */
  subscription: AdminProviderSubscriptionSnapshot;
  /** Provider wallet balance in EGP. */
  walletBalanceEgp: number;
  /** Lifetime provider earnings in EGP. */
  totalEarningsEgp: number;
  /** Estimated platform commission generated in EGP. */
  platformCommissionEgp: number;
  /** Total models owned by the provider. */
  totalModels: number;
  /** Total public models owned by the provider. */
  publicModels: number;
  /** Total LLM models owned by the provider. */
  llmModels: number;
  /** Provider account creation timestamp. */
  createdAt: string;
}

/**
 * Simple pagination metadata used by admin list endpoints.
 */
export interface AdminPaginationMeta {
  /** Current page number. */
  page: number;
  /** Page size. */
  limit: number;
  /** Total matched rows. */
  total: number;
  /** Total number of pages. */
  totalPages: number;
}

/**
 * Paginated provider list payload.
 */
export interface AdminProvidersListResponse {
  /** Provider rows for the requested page. */
  data: AdminProviderListItem[];
  /** Pagination metadata. */
  meta: AdminPaginationMeta;
}

/**
 * Per-model summary shown inside provider details.
 */
export interface AdminProviderModelSummary {
  /** Model UUID. */
  id: string;
  /** Model name. */
  name: string;
  /** Model type. */
  type: string;
  /** Visibility flag. */
  isPublic: boolean;
  /** Total requests logged for the model. */
  totalRequests: number;
  /** Provider earnings generated by the model. */
  revenueGeneratedEgp: number;
  /** Latest model log timestamp if available. */
  lastUsedAt: string | null;
  /** Model creation timestamp. */
  createdAt: string;
}

/**
 * Recent ledger/payment item shown in provider details.
 */
export interface AdminProviderTransactionSummary {
  /** Transaction UUID. */
  id: string;
  /** Transaction type. */
  type: string;
  /** Transaction amount. */
  amount: number;
  /** Transaction currency. */
  currency: string;
  /** Ledger status. */
  status: string;
  /** Reference/source text. */
  source: string | null;
  /** Transaction creation timestamp. */
  createdAt: string;
}

/**
 * Audit event projection for admin details pages.
 */
export interface AdminAuditEventSummary {
  /** Audit log UUID. */
  id: string;
  /** Actor admin UUID. */
  actorAdminId: string;
  /** Action name. */
  action: string;
  /** Human-readable description/reason. */
  reason: string | null;
  /** Serialized before snapshot. */
  before: Record<string, unknown> | null;
  /** Serialized after snapshot. */
  after: Record<string, unknown> | null;
  /** Event creation timestamp. */
  createdAt: string;
}

/**
 * Detailed provider payload powering the admin provider details page.
 */
export interface AdminProviderDetailsResponse {
  /** Account UUID. */
  id: string;
  /** Provider display name. */
  providerName: string;
  /** Owner snapshot. */
  owner: AdminProviderOwnerSummary;
  /** Assigned tier name. */
  currentTier: string;
  /** Provider lifecycle status. */
  providerStatus: string;
  /** Derived subscription snapshot. */
  subscription: AdminProviderSubscriptionSnapshot;
  /** Provider wallet balance. */
  walletBalanceEgp: number;
  /** Lifetime provider earnings. */
  totalEarningsEgp: number;
  /** Estimated commission generated. */
  platformCommissionEgp: number;
  /** Subscription payments paid in total. */
  subscriptionRevenueEgp: number;
  /** Total inferred requests across owned models. */
  totalInferenceRequests: number;
  /** Last observed activity timestamp. */
  lastActiveAt: string | null;
  /** Provider account creation time. */
  createdAt: string;
  /** Tier utilization breakdown. */
  utilization: Record<
    string,
    { used: number; limit: number | null; remaining: number | null }
  >;
  /** Provider models. */
  models: AdminProviderModelSummary[];
  /** Recent transactions/payments. */
  recentTransactions: AdminProviderTransactionSummary[];
  /** Recent audit events. */
  auditLog: AdminAuditEventSummary[];
  /** Lifecycle notes. */
  notes: string | null;
  /** Override notes. */
  customNotes: string | null;
}
