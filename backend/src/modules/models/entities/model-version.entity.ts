import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  UpdateDateColumn,
  ManyToOne,
  OneToMany,
} from 'typeorm';
import { Model } from './model.entity';
import { User } from '../../users/entities/user.entity';
import { Deployment } from '../../deployments/entities/deployment.entity';
import { VersionStatus } from '../enums/version-status.enum';
import { VersionReviewStatus } from '../enums/version-review-status.enum';
import { ModelVersionTestCase } from './model-version-test-case.entity';

/**
 * Database table representation of a specific ML model iteration.
 * Tracks uploaded files (model, scaler, scripts), build status, and associated deployments.
 */
@Entity('model_versions')
export class ModelVersion {
  /**
   * Unique UUID identifier generated by the database.
   */
  @PrimaryGeneratedColumn('uuid')
  id: string;

  /**
   * Parent model registry template this iteration belongs to.
   */
  @ManyToOne(() => Model, (model) => model.versions, { onDelete: 'CASCADE' })
  model: Model;

  /**
   * User who uploaded this version inside the provider organization workflow.
   */
  @ManyToOne(() => User, { nullable: true })
  uploadedBy: User | null;

  /**
   * Incrementing version sequence number.
   */
  @Column()
  versionNumber: number;

  /**
   * Active build status indicating package deployment readiness.
   */
  @Column({
    type: 'varchar',
    enum: VersionStatus,
    default: VersionStatus.UPLOADED,
  })
  status: VersionStatus;

  /**
   * Pull-request style review status for organization-owned versions.
   */
  @Column({
    name: 'review_status',
    type: 'varchar',
    enum: VersionReviewStatus,
    default: VersionReviewStatus.NOT_REQUIRED,
  })
  reviewStatus: VersionReviewStatus;

  /**
   * Maintainer/owner who reviewed the submitted version.
   */
  @ManyToOne(() => User, { nullable: true })
  reviewedBy: User | null;

  /**
   * Reviewer decision comment shown in the organization history.
   */
  @Column({ name: 'review_comment', type: 'text', nullable: true })
  reviewComment: string | null;

  /**
   * Timestamp of the last approval/decline decision.
   */
  @Column({ name: 'reviewed_at', type: 'timestamp', nullable: true })
  reviewedAt: Date | null;

  /**
   * Storage location path for the primary serialization bundle (e.g. model.pkl).
   */
  @Column({ nullable: false })
  modelFilePath: string;

  /**
   * Optional storage path for scaler serialization artifact.
   */
  @Column({ type: 'varchar', nullable: true })
  scalerFilePath: string | null;

  /**
   * Optional storage path for data preprocessing python scripts.
   */
  @Column({ type: 'varchar', nullable: true })
  preprocessFilePath: string | null;

  /**
   * Optional storage path for prediction output post-processing scripts.
   */
  @Column({ type: 'varchar', nullable: true })
  postprocessFilePath: string | null;

  /**
   * Sample JSON structure payload used for model sandbox prediction testing.
   */
  @Column({ type: 'text', nullable: true })
  examplePayload: string | null;

  /**
   * Predicted sample result block structure corresponding to the example payload.
   */
  @Column({ type: 'text', nullable: true })
  expectedResult: string | null;

  /**
   * Output trace log message captured when container building fails.
   */
  @Column({ type: 'text', nullable: true })
  errorMessage: string | null;

  /**
   * Build progress percentage (0-100) updated during the containerization pipeline.
   */
  @Column({ type: 'int', default: 0 })
  buildProgress: number;

  /**
   * Collection of deployments spawned using this version container.
   */
  @OneToMany(() => Deployment, (deployment) => deployment.modelVersion)
  deployments: Deployment[];

  /**
   * Saved reviewer test cases attached to this version.
   */
  @OneToMany(() => ModelVersionTestCase, (testCase) => testCase.version)
  testCases: ModelVersionTestCase[];

  /**
   * Timestamp record indicating when this specific version upload was initialized.
   */
  @CreateDateColumn()
  createdAt: Date;

  /**
   * Timestamp record indicating when this specific version build was last updated.
   */
  @UpdateDateColumn()
  updatedAt: Date;
}
