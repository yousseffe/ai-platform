import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  UpdateDateColumn,
  ManyToOne,
  OneToMany,
} from 'typeorm';
import { User } from '../../users/entities/user.entity';
import { Organization } from '../../organizations/entities/organization.entity';
import { ModelVersion } from './model-version.entity';
import { ModelType } from '../enums/model-type.enum';
import { TaskType } from '../enums/task-type.enum';
import { Framework } from '../enums/framework.enum';

/**
 * Database table representation of an ML model registry.
 * Groups model versions and links ownership to either a personal user workspace
 * or a shared organization workspace.
 */
@Entity('models')
export class Model {
  /**
   * Unique UUID identifier generated by the database.
   */
  @PrimaryGeneratedColumn('uuid')
  id: string;

  /**
   * Label of the machine learning model.
   */
  @Column()
  name: string;

  /**
   * Optional long-form explanation describing the model's domain and usage.
   */
  @Column({ type: 'varchar', nullable: true })
  description: string | null;

  /**
   * Core type classification of the model.
   */
  @Column({
    type: 'varchar',
    enum: ModelType,
    default: ModelType.TABULAR,
  })
  type: ModelType;

  /**
   * The specific task executed by this model.
   */
  @Column({
    type: 'varchar',
    enum: TaskType,
    default: TaskType.OTHER,
  })
  taskType: TaskType;

  /**
   * The framework engine utilized by this model.
   */
  @Column({
    type: 'varchar',
    enum: Framework,
    default: Framework.CUSTOM,
  })
  framework: Framework;

  /**
   * User account record of the member who originally created this model entry.
   */
  @ManyToOne(() => User)
  user: User;

  /**
   * Optional organization workspace that owns and governs this model.
   */
  @ManyToOne(() => Organization, { nullable: true })
  organization: Organization | null;

  /**
   * Collection of uploaded, containerized, and failed versions registered under this model template.
   */
  @OneToMany(() => ModelVersion, (version) => version.model)
  versions: ModelVersion[];

  /**
   * Model complexity tier size classification (e.g. SMALL, MEDIUM, LARGE) selected by provider.
   */
  @Column({ type: 'varchar', default: 'SMALL' })
  tier: string;

  /**
   * The cost in credits charged to the consumer for each prediction request.
   */
  @Column({
    name: 'cost_per_request',
    type: 'decimal',
    precision: 10,
    scale: 2,
    default: 0.0,
  })
  costPerRequest: number;

  /**
   * The percentage of the cost per request that is credited to the provider's wallet.
   */
  @Column({ name: 'provider_share_percent', type: 'integer', default: 80 })
  providerSharePercent: number;

  /**
   * The total EGP earnings generated by this model for the provider.
   */
  @Column({
    name: 'total_earnings',
    type: 'decimal',
    precision: 12,
    scale: 4,
    default: 0.0,
  })
  totalEarnings: number;

  /**
   * Flag indicating whether the model uses customized pricing instead of global default rates.
   */
  @Column({ name: 'has_custom_pricing', type: 'boolean', default: false })
  hasCustomPricing: boolean;

  /**
   * Visibility flag indicating whether this model is listed in the public marketplace.
   */
  @Column({ type: 'boolean', default: false })
  isPublic: boolean;

  /**
   * Marketplace trust flag granted after organization maintainer approval.
   */
  @Column({ name: 'marketplace_verified', type: 'boolean', default: false })
  marketplaceVerified: boolean;

  /**
   * The average star rating calculated from user reviews.
   */
  @Column({
    name: 'average_rating',
    type: 'decimal',
    precision: 3,
    scale: 2,
    default: 0.0,
  })
  averageRating: number;

  /**
   * The total count of reviews/comments submitted for this model.
   */
  @Column({ name: 'review_count', type: 'integer', default: 0 })
  reviewCount: number;

  /**
   * Timestamp record indicating when this model template registry was initialized.
   */
  @CreateDateColumn()
  createdAt: Date;

  /**
   * Timestamp record indicating when this model template metadata was last altered.
   */
  @UpdateDateColumn()
  updatedAt: Date;
}
