import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  UpdateDateColumn,
  ManyToOne,
  OneToMany,
} from 'typeorm';
import { User } from '../../users/entities/user.entity';
import { ModelVersion } from './model-version.entity';
import { ModelType } from '../enums/model-type.enum';
import { TaskType } from '../enums/task-type.enum';
import { Framework } from '../enums/framework.enum';

/**
 * Database table representation of an ML model registry.
 * Groups model versions and links ownership to a platform User.
 */
@Entity('models')
export class Model {
  /**
   * Unique UUID identifier generated by the database.
   */
  @PrimaryGeneratedColumn('uuid')
  id: string;

  /**
   * Label of the machine learning model.
   */
  @Column()
  name: string;

  /**
   * Optional long-form explanation describing the model's domain and usage.
   */
  @Column({ type: 'varchar', nullable: true })
  description: string | null;

  /**
   * Core type classification of the model.
   */
  @Column({
    type: 'varchar',
    enum: ModelType,
    default: ModelType.TABULAR,
  })
  type: ModelType;

  /**
   * The specific task executed by this model.
   */
  @Column({
    type: 'varchar',
    enum: TaskType,
    default: TaskType.OTHER,
  })
  taskType: TaskType;

  /**
   * The framework engine utilized by this model.
   */
  @Column({
    type: 'varchar',
    enum: Framework,
    default: Framework.CUSTOM,
  })
  framework: Framework;

  /**
   * Owner user account record who registered this model context.
   */
  @ManyToOne(() => User)
  user: User;

  /**
   * Collection of uploaded, containerized, and failed versions registered under this model template.
   */
  @OneToMany(() => ModelVersion, (version) => version.model)
  versions: ModelVersion[];

  /**
   * Timestamp record indicating when this model template registry was initialized.
   */
  @CreateDateColumn()
  createdAt: Date;

  /**
   * Timestamp record indicating when this model template metadata was last altered.
   */
  @UpdateDateColumn()
  updatedAt: Date;
}
